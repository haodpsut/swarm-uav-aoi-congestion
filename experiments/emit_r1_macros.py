"""Sinh macro LaTeX cho MOI con so moi cua vong sua R1, tu chinh cac CSV.

⛔ VI SAO. Bai nay chua co he macro nao: moi con so o ban da nop deu GO TAY vao .tex.
Lop loi do da cat o bai khac (mot con so headline chep tay 12 lan, va mot con so mang
NHAN sai o 8 cho). Voi vong sua nay, moi so MOI phai co DUNG MOT cho o, va cho do la
tep sinh ra tu du lieu.

Chay sau run_all_r1.py:
    python experiments/emit_r1_macros.py    ->  results/tables/r1_macros.tex

Ban thao chi duoc dung \\newcommand tu tep nay, khong duoc go so.
"""
import csv
import math
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "results")
OUT = os.path.join(RES, "tables")


def rd(n):
    with open(os.path.join(RES, n)) as f:
        return list(csv.DictReader(f))


def main():
    os.makedirs(OUT, exist_ok=True)
    L = ["% Auto-generated by experiments/emit_r1_macros.py -- KHONG sua tay",
         "% Moi con so MOI cua vong sua R1 sinh tu day. Go tay o cho khac la loi."]

    # ---- Diem 6: dao nguoc dat tram, tach theo phan bo cong ------------------
    r = rd("prop2_placement.csv")
    g = [float(x["gain_pct"]) for x in r]
    same = [float(x["gain_pct"]) for x in r if x["ports_differ"] in ("0", "False")]
    diff = [float(x["gain_pct"]) for x in r if x["ports_differ"] in ("1", "True")]
    L += [r"\newcommand{\rSeeds}{%d}" % len(r),
          r"\newcommand{\rGainMean}{%.1f}" % st.mean(g),
          r"\newcommand{\rSamePortsN}{%d}" % len(same),
          r"\newcommand{\rSamePortsMean}{%.1f}" % st.mean(same),
          r"\newcommand{\rSamePortsMed}{%.1f}" % st.median(same),
          r"\newcommand{\rSamePortsWins}{%d}" % sum(1 for x in same if x > 0),
          r"\newcommand{\rDiffPortsN}{%d}" % len(diff),
          r"\newcommand{\rDiffPortsMean}{%.1f}" % st.mean(diff)]

    # ---- Diem 7b: cac con so CU cua §VI-D, truoc day GO TAY ------------------
    # ⛔ Ban da nop in "14.8% on average" trong khi trung binh that la 14.69%, va
    # chu thich Hinh 6 viet "on every seed" trong khi co MOT seed hoa dung bang.
    # Ca hai deu la hau qua cua viec go tay. Dua chung ve macro luon.
    L += [r"\newcommand{\rGainStrictWins}{%d}" % sum(1 for x in g if x > 1e-9),
          r"\newcommand{\rGainTies}{%d}" % sum(1 for x in g if abs(x) <= 1e-9),
          r"\newcommand{\rGainLosses}{%d}" % sum(1 for x in g if x < -1e-9),
          r"\newcommand{\rGainMed}{%.1f}" % st.median(g),
          r"\newcommand{\rSitesDiffer}{%d}"
          % sum(1 for x in r if x["sites_differ"] in ("1", "True"))]

    # ---- Diem 2: tinh duy nhat cua M* va gia thiet loi roi rac ---------------
    r = rd("prop1_uniqueness.csv")
    L += [r"\newcommand{\rUniqCaps}{%d}" % len(r),
          r"\newcommand{\rUniqMulti}{%d}" % sum(1 for x in r if int(x["n_argmin"]) > 1),
          r"\newcommand{\rUniqInterior}{%d}" % sum(int(x["interior"]) for x in r),
          r"\newcommand{\rUniqSepMin}{%.2f}" % min(float(x["sep_pct"]) for x in r),
          r"\newcommand{\rUniqSecondDiffs}{%d}" % sum(int(x["n_diff"]) for x in r),
          r"\newcommand{\rUniqViol}{%d}" % sum(int(x["n_violations"]) for x in r),
          r"\newcommand{\rUniqViolMC}{%d}"
          % sum(int(x["n_violations_beyond_mc"]) for x in r)]

    # ---- Diem 7c: khoang trong toi uu, truoc day cung GO TAY -----------------
    r = rd("optimality_gap.csv")
    ex = [x for x in r if int(x["optimal_hits"]) == int(x["n_seeds"])]
    top = max(r, key=lambda x: int(x["M"]))
    L += [r"\newcommand{\rOptSeeds}{%d}" % int(r[0]["n_seeds"]),
          r"\newcommand{\rOptExactMax}{%d}" % max(int(x["M"]) for x in ex),
          r"\newcommand{\rOptTopM}{%d}" % int(top["M"]),
          r"\newcommand{\rOptTopMean}{%.2f}" % float(top["gap_mean_pct"]),
          r"\newcommand{\rOptTopMax}{%.2f}" % float(top["gap_max_pct"]),
          r"\newcommand{\rOptTopHits}{%d}" % int(top["optimal_hits"])]

    # ---- Diem 5: thu hang duoi M/M so M/D -----------------------------------
    r = rd("prop2_ranking_md.csv")
    flips = sum(1 for x in r if x["flipped"] == "1")
    covwin = sum(1 for x in r if "cov" in (x["winner_mm"], x["winner_md"]))
    ties = sum(1 for x in r if "tie" in (x["winner_mm"], x["winner_md"]))
    # Phan bien khong chi hoi THU HANG, ho con hoi "reported performance gains remain
    # consistent" hay khong. Do luon loi ich trung binh duoi tung mo hinh hang doi.
    gmm = [100 * (float(x["aoi_cov_mm"]) - float(x["aoi_traf_mm"])) / float(x["aoi_cov_mm"])
           for x in r]
    gmd = [100 * (float(x["aoi_cov_md"]) - float(x["aoi_traf_md"])) / float(x["aoi_cov_md"])
           for x in r]
    L += [r"\newcommand{\rRankGainMM}{%.1f}" % st.mean(gmm),
          r"\newcommand{\rRankGainMD}{%.1f}" % st.mean(gmd),
          r"\newcommand{\rRankGainDelta}{%.1f}" % abs(st.mean(gmm) - st.mean(gmd)),
          r"\newcommand{\rRankFlip}{%d}" % flips,
          r"\newcommand{\rRankCovWins}{%d}" % covwin,
          r"\newcommand{\rRankTies}{%d}" % ties]

    # ---- Diem 3: gia cua viec co dinh sub-field ------------------------------
    r = rd("joint_reopt_check.csv")
    gg = [float(x["gain_pct"]) for x in r if math.isfinite(float(x["gain_pct"]))]
    L += [r"\newcommand{\rJointMean}{%.2f}" % st.mean(gg),
          r"\newcommand{\rJointMax}{%.2f}" % max(gg),
          r"\newcommand{\rJointWorse}{%d}" % sum(1 for x in gg if x < 0),
          r"\newcommand{\rJointBetter}{%d}" % sum(1 for x in gg if x > 0.05)]

    # ---- Diem 1: cho trung binh so voi phan vi cao ---------------------------
    r = rd("aoi_metric_gap.csv")
    p95 = [float(x["ratio_p95"]) for x in r if math.isfinite(float(x["ratio_p95"]))]
    mx = [float(x["ratio_max"]) for x in r if math.isfinite(float(x["ratio_max"]))]
    sat = [x for x in r if x["M"] == "12" and x["c"] == "2"]
    L += [r"\newcommand{\rPninefiveMed}{%.2f}" % st.median(p95),
          r"\newcommand{\rMaxMed}{%.2f}" % st.median(mx),
          r"\newcommand{\rMaxHi}{%.1f}" % max(mx),
          r"\newcommand{\rMaxSat}{%.2f}" % float(sat[0]["ratio_max"]) if sat else "",
          ]

    # ---- Diem 7: cac con so CU khac, truoc day chi ton tai tren MAN HINH ------
    # Doan §VI-A in nam con so ve DES. Chung sinh tu des_validation.py voi nguong loc
    # `des > 1.0` giay, nhung truoc day script chi IN chung ra, khong ghi tep nao. Nay
    # doc lai tu des_summary.csv do chinh script do ghi, nen nguong loc chi co MOT cho.
    r = {x["quantity"]: float(x["value"]) for x in rd("des_summary.csv")}
    L += [r"\newcommand{\rDesRelErr}{%.1f}" % r["formula_rel_err_pct"],
          r"\newcommand{\rDesFormulaN}{%d}" % int(r["formula_n"]),
          r"\newcommand{\rDesOpenOver}{%.1f}" % r["open_over_des"],
          r"\newcommand{\rDesFiniteOverReal}{%.1f}" % r["finite_over_real"],
          r"\newcommand{\rDesMdOverReal}{%.1f}" % r["md_over_real"],
          r"\newcommand{\rDesConsHits}{%d}" % int(r["conservative_hits"]),
          r"\newcommand{\rDesRealN}{%d}" % int(r["real_n"])]

    # ---- Diem 7: dai gia tri o §VI-F, truoc day TRON HAI DUONG CO SO ----------
    # ⛔ Ban da nop viet "advantage over the single pooled station AND the
    # coverage-optimal placement ... by 10.2 to 12.7%", nhung dai do CHI la cua duong
    # co so single. Doi voi coverage, day thap nhat la 8.7%, tuc thap hon san da neu.
    r = rd("scale.csv")
    gs = [100 * (float(x["single_min"]) - float(x["proposed_min"])) / float(x["single_min"])
          for x in r]
    gc = [100 * (float(x["coverage_min"]) - float(x["proposed_min"])) / float(x["coverage_min"])
          for x in r]
    L += [r"\newcommand{\rScaleSingleLo}{%.1f}" % min(gs),
          r"\newcommand{\rScaleSingleHi}{%.1f}" % max(gs),
          r"\newcommand{\rScaleCovLo}{%.1f}" % min(gc),
          r"\newcommand{\rScaleCovHi}{%.1f}" % max(gc)]

    # ---- Bang ablation: ca NAM dong deu go tay, dua ve macro -----------------
    # Cong mot-cho-o bat duoc khi \rOneUavSwarmAoi ra dung 41.1, tuc bang dang lap lai
    # mot dai luong da co macro. Bang nao con go tay thi som muon lech.
    r = rd("joint_ablation.csv")
    for key, mac in (("proposed", "AblProposed"), ("no_cetsp", "AblNoCetsp"),
                     ("single_station", "AblSingleStation"),
                     ("coverage", "AblCoverage"), ("roundrobin", "AblRoundRobin")):
        L.append(r"\newcommand{\r%s}{%.1f}"
                 % (mac, st.mean(float(x[key]) for x in r) / 60.0))

    # ---- Doc ngoai 26/08: duong co so MOT UAV, bai hua ma khong giao ---------
    r = rd("single_uav_baseline.csv")
    one = [float(x["single_uav_min"]) for x in r]
    sw = [float(x["swarm_min"]) for x in r]
    gn = [float(x["gain_pct"]) for x in r]
    L += [r"\newcommand{\rOneUavAoi}{%.1f}" % st.mean(one),
          r"\newcommand{\rOneUavSwarmAoi}{%.1f}" % st.mean(sw),
          r"\newcommand{\rOneUavGain}{%.1f}" % st.mean(gn),
          r"\newcommand{\rOneUavGainLo}{%.1f}" % min(gn),
          r"\newcommand{\rOneUavSeeds}{%d}" % len(r),
          r"\newcommand{\rOneUavLosses}{%d}" % sum(1 for x in gn if x < 0)]

    # ---- Doc ngoai 26/08: hieu ung thay cho p-value o san --------------------
    r = rd("ablation_effect.csv")[0]
    L += [r"\newcommand{\rAblPairs}{%d}" % int(r["pairs"]),
          r"\newcommand{\rAblWins}{%d}" % int(r["wins"]),
          r"\newcommand{\rAblEffect}{%.1f}" % float(r["effect_mean_pct"]),
          r"\newcommand{\rAblCiLo}{%.1f}" % float(r["ci_lo_pct"]),
          r"\newcommand{\rAblCiHi}{%.1f}" % float(r["ci_hi_pct"]),
          r"\newcommand{\rAblMin}{%.1f}" % float(r["effect_min_pct"]),
          r"\newcommand{\rAblMax}{%.1f}" % float(r["effect_max_pct"])]

    # ---- Doc ngoai 26/08: DINH so voi TRUNG BINH THEO THOI GIAN ---------------
    r = rd("paoi_vs_timeavg.csv")
    rt = [float(x["ratio"]) for x in r]
    L += [r"\newcommand{\rPaoiRatioLo}{%.2f}" % min(rt),
          r"\newcommand{\rPaoiRatioHi}{%.2f}" % max(rt),
          r"\newcommand{\rPaoiRatioMed}{%.2f}" % st.median(rt),
          r"\newcommand{\rPaoiConfigs}{%d}" % len(r),
          r"\newcommand{\rPaoiCvHi}{%.3f}" % max(float(x["cv"]) for x in r)]

    # ---- Diem 4: bien kha dat tram ------------------------------------------
    r = rd("reach_margin.csv")
    mn = [float(x["margin_min"]) for x in r]
    L += [r"\newcommand{\rReachMin}{%.1f}" % min(mn),
          r"\newcommand{\rReachSeeds}{%d}" % len(r),
          r"\newcommand{\rReachInfeasible}{%d}" % sum(1 for x in r if x["feasible"] == "0")]

    L = [x for x in L if x]
    p = os.path.join(OUT, "r1_macros.tex")
    open(p, "w").write("\n".join(L) + "\n")
    bad = [x for x in L if x.startswith(r"\newcommand") and
           any(ch.isdigit() for ch in x.split("}")[0])]
    print("  ✅ ghi results/tables/r1_macros.tex  (%d macro)" % (len(L) - 2))
    if bad:
        print("  ⛔ %d TEN MACRO CHUA CHU SO -> LaTeX vo preamble:" % len(bad))
        for b in bad:
            print("     %s}" % b.split("}")[0])
        return 1
    print("     kiem ten: 0/%d macro chua chu so ✅" % (len(L) - 2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
