"""Bang tham so, SINH TU CHINH MA NGUON chu khong go tay.

Nguoi doc ngoai (26/08): *"Critical values remain undeclared: all rotary-wing power
constants, communication parameters, coverage weights, and simulation specifications
needed for reproducibility."* Dung: bai neu $V$, $H$, pin, thoi gian sac, con tam hang
so cua mo hinh cong suat va toan bo tham so duong truyen thi khong o dau ca. Nguoi doc
khong dung lai duoc con so nao neu thieu chung.

⛔ Va bang nay khong duoc GO TAY. Neu go, no la mot ban sao thu hai cua cac hang so
trong `src/`, va hai ban sao thi som muon lech nhau: chinh lop loi da bat trong vong sua
nay (mot tep macro co hai ban, ban thao nap nham ban cu). Script IMPORT truc tiep tu
`src/energy.py`, `src/comms.py`, `src/scenario.py`, nen bang luon la thu ma bai that su
chay.

    python experiments/emit_param_table.py  ->  results/tables/params.tex
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

import comms                                     # noqa: E402
import energy                                    # noqa: E402
from scenario import DEFAULTS, tau_charge_of     # noqa: E402


def rows():
    tau_charge = tau_charge_of(DEFAULTS["E_max"], DEFAULTS["charge_power"])
    return [
        ("Field and sensors", [
            (r"Sensors $K$", "%d" % DEFAULTS["K"], ""),
            (r"Field side $L$", "5 to 20", "km"),
            (r"Collection radius $r_c$", "200", "m"),
            (r"Payload per visit", "%.0f" % (comms.PACKET_BITS / 1e6), "Mb"),
        ]),
        ("UAV and flight", [
            (r"Cruise speed $V$", "%.0f" % DEFAULTS["V"], "m/s"),
            (r"Altitude $H$", "%.0f" % DEFAULTS["H"], "m"),
            (r"Battery $E_{\max}$", "%.1f" % (DEFAULTS["E_max"] / 3600.0), "Wh"),
            (r"Energy reserve", "%.0f" % (100 * DEFAULTS["E_reserve"]), "\\%"),
        ]),
        ("Rotary-wing power model~\\cite{zeng2019energy}", [
            (r"Blade profile $P_0$", "%.2f" % energy.P0, "W"),
            (r"Induced power $P_i$", "%.2f" % energy.Pind, "W"),
            (r"Tip speed $U_{\mathrm{tip}}$", "%.0f" % energy.U_TIP, "m/s"),
            (r"Hover induced velocity $v_0$", "%.2f" % energy.V0, "m/s"),
            (r"Fuselage drag ratio $d_0$", "%.2f" % energy.D0, ""),
            (r"Air density $\rho$", "%.3f" % energy.RHO, "kg/m$^3$"),
            (r"Rotor solidity $s$", "%.3f" % energy.S_ROTOR, ""),
            (r"Rotor disc area $A$", "%.3f" % energy.A_ROTOR, "m$^2$"),
        ]),
        ("Air-to-ground link", [
            (r"Reference gain $\beta_0$", "%.0f" % comms.BETA0_DB, "dB"),
            (r"Sensor transmit power $p_{\mathrm{tx}}$", "%.0f" % comms.P_TX_DBM, "dBm"),
            (r"Noise PSD $N_0$", "%.0f" % comms.N0_DBM_HZ, "dBm/Hz"),
            (r"Bandwidth $B$", "%.0f" % (comms.BW / 1e6), "MHz"),
        ]),
        ("Charging and placement", [
            (r"Charge power per port", "%.0f" % DEFAULTS["charge_power"], "W"),
            (r"Charge time $\tau_{\mathrm{charge}}$", "%.1f" % (tau_charge / 60.0), "min"),
            (r"Candidate sites", "$3\\times3$ grid", ""),
            (r"Open stations $S_{\max}$", "2", ""),
            (r"Total ports $C_{\mathrm{tot}}$", "4", ""),
        ]),
    ]


def main():
    out = os.path.join(ROOT, "results", "tables")
    os.makedirs(out, exist_ok=True)
    L = [r"% Auto-generated by experiments/emit_param_table.py -- KHONG sua tay.",
         r"% Moi gia tri IMPORT truc tiep tu src/. Go tay o day la tao ban sao thu hai.",
         r"\begin{table}[t]", r"  \centering",
         r"  \caption{Simulation parameters. All values are imported directly from the "
         r"artifact source by the script that generates this table, so the table cannot "
         r"drift from the code that produced the results.}",
         r"  \label{tab:params}", r"  \begin{tabular}{llr}", r"    \toprule",
         r"    Parameter & Value & Unit \\"]
    for group, items in rows():
        L += [r"    \midrule", r"    \multicolumn{3}{l}{\emph{%s}} \\" % group]
        for name, val, unit in items:
            L.append(r"    %s & %s & %s \\" % (name, val, unit if unit else "--"))
    L += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]

    p = os.path.join(out, "params.tex")
    open(p, "w").write("\n".join(L) + "\n")
    n = sum(len(v) for _, v in rows())
    print("  ✅ ghi results/tables/params.tex  (%d tham so, %d nhom)"
          % (n, len(rows())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
