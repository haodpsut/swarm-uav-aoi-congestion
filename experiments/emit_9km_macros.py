"""Sinh macro cho ket qua 9 km / 3 tram. So headline phai co MOT CHO O."""
import csv, math, os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
RES=os.path.join(ROOT,"results")
def f(x):
    try:
        v=float(x); return v if math.isfinite(v) else None
    except Exception: return None
r=list(csv.DictReader(open(os.path.join(RES,"ablation_9km_3st.csv"))))
col=lambda m: [f(x[m]) for x in r]
prop, base = col("proposed"), col("no_cetsp")
cap=[(a,b) for a,b in zip(prop,base) if a and b]
n_kt=sum(1 for x in prop if x)
loi=100.0*(sum(b for _,b in cap)-sum(a for a,_ in cap))/sum(b for _,b in cap)
xau=min(100.0*(b-a)/b for a,b in cap)
thang=sum(1 for a,b in cap if a<b)
tb=sum(a for a,_ in cap)/len(cap)/60.0
L=[r"% Auto-generated by experiments/emit_9km_macros.py -- KHONG sua tay",
   r"\newcommand{\rNineFeas}{%d}" % n_kt,
   r"\newcommand{\rNineSeeds}{%d}" % len(r),
   r"\newcommand{\rNineGain}{%.1f}" % loi,
   r"\newcommand{\rNineWorst}{%.1f}" % xau,
   r"\newcommand{\rNineWins}{%d}" % thang,
   r"\newcommand{\rNinePairs}{%d}" % len(cap),
   r"\newcommand{\rNineAoI}{%.1f}" % tb,
   r"\newcommand{\rNineSingleFeas}{%d}" % sum(1 for x in col("single_station") if x),
   r"\newcommand{\rNineRRFeas}{%d}" % sum(1 for x in col("roundrobin") if x)]
out=os.path.join(RES,"tables","r2_9km_macros.tex")
open(out,"w").write("\n".join(L)+"\n")
print("ghi %s (%d macro)" % (os.path.relpath(out,ROOT), len(L)-1))
for x in L[1:]: print("   "+x)
