"""Sinh macro cho ket qua 9 km / 3 tram. So headline phai co MOT CHO O."""
import csv, math, os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
RES=os.path.join(ROOT,"results")
def f(x):
    try:
        v=float(x); return v if math.isfinite(v) else None
    except Exception: return None
r=list(csv.DictReader(open(os.path.join(RES,"ablation_9km_3st.csv"))))
col=lambda m: [f(x[m]) for x in r]
prop, base = col("proposed"), col("no_cetsp")
cap=[(a,b) for a,b in zip(prop,base) if a and b]
n_kt=sum(1 for x in prop if x)
loi=100.0*(sum(b for _,b in cap)-sum(a for a,_ in cap))/sum(b for _,b in cap)
xau=min(100.0*(b-a)/b for a,b in cap)
thang=sum(1 for a,b in cap if a<b)
tb=sum(a for a,_ in cap)/len(cap)/60.0
L=[r"% Auto-generated by experiments/emit_9km_macros.py -- KHONG sua tay",
   r"\newcommand{\rNineFeas}{%d}" % n_kt,
   r"\newcommand{\rNineSeeds}{%d}" % len(r),
   r"\newcommand{\rNineGain}{%.1f}" % loi,
   r"\newcommand{\rNineWorst}{%.1f}" % xau,
   r"\newcommand{\rNineWins}{%d}" % thang,
   r"\newcommand{\rNinePairs}{%d}" % len(cap),
   r"\newcommand{\rNineAoI}{%.1f}" % tb,
   r"\newcommand{\rNineSingleFeas}{%d}" % sum(1 for x in col("single_station") if x),
   r"\newcommand{\rNineRRFeas}{%d}" % sum(1 for x in col("roundrobin") if x)]

# ---- kha thi cua ABLATION, va cau hoi "co hat nao ablation bay duoc ma de xuat thi khong"
# Nguoi doc ngoai 03/10 goi day la "the one item a referee is likely to ask for".
kt_prop = {int(x["seed"]) for x, v in zip(r, prop) if v}
kt_abl = {int(x["seed"]) for x, v in zip(r, base) if v}
L += [r"\newcommand{\rNineAblFeas}{%d}" % len(kt_abl),
      r"\newcommand{\rNineAblOnly}{%d}" % len(kt_abl - kt_prop),
      r"\newcommand{\rNineExcl}{%d}" % (len(r) - len(kt_prop))]

# ⛔ CONG, khong phai ghi chu. Cau o muc VI-J viet "the same seeds" chi DUNG khi hai tap
# bang nhau. Neu mot lan chay lai lam chung lech thi khong duoc im lang de cau van cu, da
# sai, di tiep: dung o day va bat nguoi viet sua cau. Lop loi 29, ket luan dinh tinh
# nguoc voi macro ben canh.
if kt_prop != kt_abl:
    sys.exit("⛔ tap hat giong kha thi KHAC nhau (de xuat %s, ablation %s): cau \"the same "
             "seeds\" o muc VI-J khong con dung, phai viet lai TRUOC khi dung lai bai"
             % (sorted(kt_prop), sorted(kt_abl)))

# ---- chan doan 9 hat BI LOAI (experiments/chan_doan_hat_bi_loai.py) ----
cd = os.path.join(RES, "chan_doan_9km_hat_bi_loai.txt")
if os.path.exists(cd):
    d = dict(l.split("=", 1) for l in open(cd).read().splitlines() if "=" in l)
    L += [r"\newcommand{\rNineCovKt}{%.2f}" % float(d["bk_kha_thi_max_km"]),
          r"\newcommand{\rNineCovBl}{%.2f}" % float(d["bk_bi_loai_min_km"]),
          r"\newcommand{\rNineGainKept}{%.1f}" % float(d["loi_kha_thi_pc"]),
          r"\newcommand{\rNineGainExcl}{%.1f}" % float(d["loi_bi_loai_pc"]),
          r"\newcommand{\rNineGainP}{%.2f}" % float(d["p_tron"])]
out=os.path.join(RES,"tables","r2_9km_macros.tex")
open(out,"w").write("\n".join(L)+"\n")
print("ghi %s (%d macro)" % (os.path.relpath(out,ROOT), len(L)-1))
for x in L[1:]: print("   "+x)
